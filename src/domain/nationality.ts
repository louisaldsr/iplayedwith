/**
 * Smart constructor for Nationality.
 * Validates the raw string against the code list above (case-insensitive).
 *
 * @throws if the code is not a recognized nationality code.
 */
export const Nationality = (raw: string): Nationality => {
  const code = raw.toUpperCase();
  if (!ALPHA2_CODES.has(code)) throw new Error(`Invalid nationality code: ${raw}`);
  return code as Nationality;
};
